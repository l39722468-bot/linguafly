export function ShareButton({ title, description }: ShareButtonProps) {
  const [isOpen, setIsOpen] = useState(false);
  const [copied, setCopied] = useState(false);
  const menuRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    function handleClickOutside(e: MouseEvent) {
      if (menuRef.current && !menuRef.current.contains(e.target as Node)) {
        setIsOpen(false);
      }
    }
    if (isOpen) {
      document.addEventListener("mousedown", handleClickOutside);
    }
    return () => document.removeEventListener("mousedown", handleClickOutside);
  }, [isOpen]);

  const currentUrl = typeof window !== "undefined" ? window.location.href : "";

  const handleShare = (network: (typeof socialNetworks)[number]) => {
    if (!network.getUrl) {
      handleCopyLink(
        network.key === "instagram"
          ? "Enlace copiado. Pégalo en tu historia o bio de Instagram."
          : "Enlace copiado. Compártelo en TikTok."
      );
      return;
    }
    const url = network.getUrl(currentUrl, title);
    window.open(url, "_blank", "noopener,noreferrer,width=600,height=500");
    setIsOpen(false);
  };

  const handleCopyLink = (message?: string) => {
    navigator.clipboard.writeText(currentUrl).then(() => {
      setCopied(true);
      setTimeout(() => {
        setCopied(false);
        setIsOpen(false);
      }, 2000);
    });
  };

  const handleNativeShare = () => {
    if (navigator.share) {
      navigator
        .share({ title, text: description, url: currentUrl })
        .catch(() => {});
    }
  };

  return (
    <div className="relative" ref={menuRef}>
      <button
        onClick={() => setIsOpen(!isOpen)}
        className="flex items-center gap-2 text-sm text-coral-600 font-semibold hover:text-coral-700 cursor-pointer transition-colors"
        type="button"
        aria-expanded={isOpen}
        aria-haspopup="true"
      >
        <svg
          className="w-4 h-4"
          fill="none"
          stroke="currentColor"
          viewBox="0 0 24 24"
          strokeWidth={2}
        >
          <path
            strokeLinecap="round"
            strokeLinejoin="round"
            d="M8.684 13.342C8.886 12.938 9 12.482 9 12c0-.482-.114-.938-.316-1.342m0 2.684a3 3 0 1 1 0-2.684m0 2.684l6.632 3.316m-6.632-6l6.632-3.316m0 0a3 3 0 1 0 5.367-2.684 3 3 0 0 0-5.367 2.684zm0 9.316a3 3 0 1 0 5.368 2.684 3 3 0 0 0-5.368-2.684z"
          />
        </svg>
        Compartir
      </button>

      {isOpen && (
        <div className="absolute right-0 top-full mt-2 w-64 bg-white rounded-2xl shadow-xl border border-slate-100 py-2 z-50 animate-in fade-in slide-in-from-top-2 duration-200">
          <p className="px-4 py-2 text-xs font-bold text-slate-400 uppercase tracking-wider">
            Compartir en
          </p>

          {socialNetworks.map((network) => (
            <button
              key={network.key}
              onClick={() => handleShare(network)}
              className={`w-full flex items-center gap-3 px-4 py-2.5 text-sm font-medium text-slate-700 transition-all ${network.color} cursor-pointer`}
              type="button"
            >
              {network.icon}
              <span>{network.name}</span>
              {!network.getUrl && (
                <span className="ml-auto text-[10px] text-slate-400 font-normal">
                  Copiar enlace
                </span>
              )}
            </button>
          ))}

          <div className="border-t border-slate-100 mt-1 pt-1">
            <button
              onClick={handleCopyLink}
              className="w-full flex items-center gap-3 px-4 py-2.5 text-sm font-medium text-slate-700 hover:bg-slate-50 transition-all cursor-pointer"
              type="button"
            >
              <svg
                className="w-5 h-5"
                fill="none"
                stroke="currentColor"
                viewBox="0 0 24 24"
                strokeWidth={2}
              >
                <path
                  strokeLinecap="round"
                  strokeLinejoin="round"
                  d="M13.19 8.688a4.5 4.5 0 0 1 1.242 7.244l-4.5 4.5a4.5 4.5 0 0 1-6.364-6.364l1.757-1.757m9.86-2.54a4.5 4.5 0 0 0-1.242-7.244l-4.5-4.5a4.5 4.5 0 0 0-6.364 6.364L4.757 8.25"
                />
              </svg>
              <span>{copied ? "¡Enlace copiado!" : "Copiar enlace"}</span>
            </button>

            {typeof navigator !== "undefined" && "share" in navigator && (
              <button
                onClick={handleNativeShare}
                className="w-full flex items-center gap-3 px-4 py-2.5 text-sm font-medium text-slate-700 hover:bg-slate-50 transition-all cursor-pointer"
                type="button"
              >
                <svg
                  className="w-5 h-5"
                  fill="none"
                  stroke="currentColor"
                  viewBox="0 0 24 24"
                  strokeWidth={2}
                >
                  <path
                    strokeLinecap="round"
                    strokeLinejoin="round"
                    d="M3 16.5v2.25A2.25 2.25 0 0 0 5.25 21h13.5A2.25 2.25 0 0 0 21 18.75V16.5m-13.5-9L12 3m0 0 4.5 4.5M12 3v13.5"
                  />
                </svg>
                <span>Más opciones...</span>
              </button>
            )}
          </div>
        </div>
      )}
    </div>
  );
}
